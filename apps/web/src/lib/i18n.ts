/**
 * The interface is English-only; Kronos itself replies in the user's language
 * (agent.language: "auto"). Strings live here so copy stays consistent.
 */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}
